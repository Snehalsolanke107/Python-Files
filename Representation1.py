 # Binary Represntation

num1 = 0B110110
print(num1)

num2 = int(num1)
print(num2) 
print("type of num2 :", type(num2))

num3 = bin(num2)
print(num3)
print("type of num3 : ", type(num3))

 # octal representation

num4 = 0o32

num5 = int(num4)
print(num5) 
print("type of num5 :", type(num5))

num6 = oct(num5)
print(num6) 
print("type of num6 :", type(num6))

 # Hexa-decimal representation

num7 = 0x32

num8 = int(num7)
print(num8) 
print("type of num8 :", type(num8))

num9 = hex(num8)
print(num9) 
print("type of num6 :", type(num9))